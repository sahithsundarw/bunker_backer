#!/usr/bin/env python3
"""End-to-end runtime harness (SPEC 11.4 step 7; V37, V38, V39).

Times the WHOLE PROCESS externally -- interpreter start, imports, model load, IO and
compute -- not an internal timer around the forward pass. Startup is ~85-95% of the
scored wall-clock (docs/decisions.md D7), so an internal timer would hide most of it.

V39 has NO threshold and may NOT be skipped: measure on whatever device is present and
LABEL the report with that device name (docs/decisions.md D10).

Writes results/runtime_report.md with a startup-vs-compute breakdown.

Owner: perf-analyst (proposes), main session (applies).
"""

from __future__ import annotations

import argparse
import platform
import re
import shlex
import statistics
import subprocess
import sys
import tempfile
import time
from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parent.parent
SUMMARY_RE = re.compile(
    r"restored\s+(?P<written>\d+)/(?P<found>\d+)\s+in\s+"
    r"(?P<internal>[0-9.]+)s\s+\((?P<rate>[0-9.]+)\s+img/s\).*"
    r"device=(?P<device>\S+)\s+precision=(?P<precision>\S+)\s+batch=(?P<batch>\d+)"
)


def _run_once(args: argparse.Namespace, output_dir: Path) -> dict[str, object]:
    cmd = [
        args.python, str(REPO_ROOT / "inference.py"),
        "--input_dir", str(Path(args.input_dir).resolve()),
        "--output_dir", str(output_dir),
        "--batch_size", str(args.batch_size),
        "--precision", args.precision,
        "--require_weights",
        "--verbose",
    ]
    if args.device:
        cmd.extend(["--device", args.device])
    if args.weights:
        cmd.extend(["--weights", str(Path(args.weights).resolve())])

    started = time.perf_counter()
    proc = subprocess.run(cmd, cwd=REPO_ROOT, text=True, capture_output=True,
                          check=False, timeout=args.timeout)
    external_s = time.perf_counter() - started
    if proc.returncode != 0:
        detail = (proc.stderr or proc.stdout).strip()[-1200:]
        raise RuntimeError(f"inference exited {proc.returncode}: {detail}")

    match = SUMMARY_RE.search(proc.stdout)
    if match is None:
        raise RuntimeError(f"could not parse inference summary from: {proc.stdout.strip()!r}")
    found = int(match.group("found"))
    written = int(match.group("written"))
    n_outputs = len(list(output_dir.rglob("*.npy")))
    if written != found or n_outputs != found:
        raise RuntimeError(
            f"incomplete run: summary={written}/{found}, output_files={n_outputs}"
        )
    internal_s = float(match.group("internal"))
    return {
        "command": cmd,
        "external_s": external_s,
        "internal_s": internal_s,
        "startup_import_s": max(0.0, external_s - internal_s),
        "images": found,
        "device": match.group("device"),
        "precision": match.group("precision"),
        "batch": int(match.group("batch")),
    }


def _render(runs: list[dict[str, object]], invocation: list[str]) -> str:
    external = [float(r["external_s"]) for r in runs]
    internal = [float(r["internal_s"]) for r in runs]
    overhead = [float(r["startup_import_s"]) for r in runs]
    n = int(runs[0]["images"])
    total = statistics.median(external)
    pipeline = statistics.median(internal)
    startup = statistics.median(overhead)
    rate = n / max(total, 1e-9)
    command = shlex.join(invocation)
    repeat_values = ", ".join(f"{v:.2f}" for v in external)
    raw_device = str(runs[0]["device"])
    if raw_device == "cpu" and platform.system() == "Darwin":
        device_label = "Local Mac CPU"
    elif raw_device == "cpu":
        device_label = "Local CPU"
    elif raw_device == "cuda":
        device_label = "Local CUDA"
    else:
        device_label = f"Local {raw_device}"
    return f"""# Runtime report

Generated by `scripts/benchmark_runtime.py` using an external subprocess timer.

## Runtime headline

**{device_label} external-process benchmark: {n} images in {total:.2f} s
({rate:.1f} img/s), batch size {runs[0]['batch']}, {runs[0]['precision']}.**

| Field | Value |
|---|---|
| Device | {platform.platform()} / inference device `{runs[0]['device']}` |
| Total end-to-end wall-clock timing | {total:.2f} s median over {len(runs)} run(s) |
| Throughput | {rate:.1f} img/s |
| Batch size | {runs[0]['batch']} |
| Precision | {runs[0]['precision']} |
| Main pipeline, including model load, IO, compute, transfers, and writes | {pipeline:.2f} s |
| Process startup/import overhead | {startup:.2f} s |
| External repeat totals | {repeat_values} s |

The external timing window begins immediately before process creation and ends after
`inference.py` exits, so it covers interpreter startup, imports, checkpoint loading, disk read,
preprocessing, transfers, model compute, post-processing, and disk writes. The main-pipeline
number is parsed from `inference.py`'s internal summary only to estimate startup/import
overhead; it is not substituted for the external headline measurement. Pure model compute is
not separately instrumented.

Command:

```bash
{command}
```
"""


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--input_dir", required=True)
    ap.add_argument("--out", default="results/runtime_report.md")
    ap.add_argument("--repeats", type=int, default=3)
    ap.add_argument("--python", default=sys.executable,
                    help="Python executable used to launch inference.py")
    ap.add_argument("--weights", default=None,
                    help="checkpoint override; inference.py's tracked default is used otherwise")
    ap.add_argument("--batch_size", type=int, default=32)
    ap.add_argument("--device", default=None)
    ap.add_argument("--precision", default="auto",
                    choices=["auto", "bf16", "fp16", "fp32"])
    ap.add_argument("--timeout", type=float, default=1800.0,
                    help="per-repeat subprocess timeout in seconds")
    raw_argv = list(argv) if argv is not None else sys.argv[1:]
    args = ap.parse_args(raw_argv)
    if args.repeats < 1:
        ap.error("--repeats must be at least 1")
    if not Path(args.input_dir).is_dir():
        ap.error(f"--input_dir is not a directory: {args.input_dir}")

    runs: list[dict[str, object]] = []
    with tempfile.TemporaryDirectory(prefix="kla-runtime-") as tmp:
        root = Path(tmp)
        for i in range(args.repeats):
            run = _run_once(args, root / f"run-{i + 1}")
            runs.append(run)
            print(f"repeat {i + 1}/{args.repeats}: {run['external_s']:.2f}s external, "
                  f"{run['internal_s']:.2f}s main pipeline")

    out = Path(args.out)
    if not out.is_absolute():
        out = REPO_ROOT / out
    out.parent.mkdir(parents=True, exist_ok=True)
    invocation = [sys.executable, str(Path(__file__).resolve()), *raw_argv]
    out.write_text(_render(runs, invocation), encoding="utf-8")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
